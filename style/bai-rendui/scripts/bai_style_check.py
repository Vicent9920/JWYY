    files = [a for a in args if not a.startswith('--')]
    if not files:
        print(__doc__); return
    do_style = ('--aigc' not in flags)
    do_aigc = ('--style' not in flags)
    for f in files:
        F = analyze(f)
        print()
        if do_style: report_style(F, f); print()
        if do_aigc: report_aigc(F, f)
        print('=' * 92)


